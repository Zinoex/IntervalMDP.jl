    mutable struct LCG
        state::UInt64
    end
    function nextfloat!(r::LCG)
        r.state = r.state * 0x5851f42d4c957f2d + 0x14057b7ef767814f
        return Float64(r.state >> 11) / 9007199254740992.0
    end
    nextint!(r::LCG, n) = 1 + floor(Int, nextfloat!(r) * n)

    # One column: reference distribution r over the support,
    # lower = r (0.5 + 0.4u₁), upper = min(r (1.1 + 0.4u₂), 1).
    function column!(rng, lower, gap)
        k = length(lower)
        for i in 1:k
            lower[i] = nextfloat!(rng) + 1e-3
        end
        s = sum(lower)
        for i in 1:k
            r = lower[i] / s
            l = r * (0.5 + 0.4 * nextfloat!(rng))
            u = min(r * (1.1 + 0.4 * nextfloat!(rng)), 1.0)
            lower[i] = l
            gap[i] = u - l
        end
        return nothing
    end

    function dense_sets(rng, n, ncols)
        lower = zeros(n, ncols)
        gap = zeros(n, ncols)
        for j in 1:ncols
            column!(rng, view(lower, :, j), view(gap, :, j))
        end
        return IntervalAmbiguitySets(lower, gap)
    end

    function sparse_sets(rng, n, ncols, k)
        I, J, L, G = Int32[], Int32[], Float64[], Float64[]
        l = zeros(k)
        g = zeros(k)
        for j in 1:ncols
            support = Int[]
            while length(support) < k
                i = nextint!(rng, n)
                i in support || push!(support, i)
            end
            sort!(support)
            column!(rng, l, g)
            append!(I, support)
            append!(J, fill(j, k))
            append!(L, l)
            append!(G, g)
        end
        lower = sparse(I, J, L, n, ncols)
        gap = sparse(I, J, G, n, ncols)
        return IntervalAmbiguitySets(lower, gap)
    end

    function random_imdp(seed; n, actions, storage, nnz = 0)
        rng = LCG(seed)
        sets =
            storage === :dense ? dense_sets(rng, n, n * actions) :
            sparse_sets(rng, n, n * actions, nnz)
        return IntervalMarkovDecisionProcess(sets, actions), rng
    end

    input_values(rng, model) =
        [nextfloat!(rng) for _ in CartesianIndices(Tuple(Int.(state_values(model))))]

    function random_states(rng, n, frac)
        m = max(1, round(Int, frac * n))
        s = Int[]
        while length(s) < m
            i = nextint!(rng, n)
            i in s || push!(s, i)
        end
        return sort!(s)
    end

    # Product with a 4-state DFA over AP = {a, b} (labels "", a, b, ab): state 1
    # (init) --a--> 2 --b--> 3 (accepting, absorbing); 1 --b--> 4 (rejecting,
    # absorbing). Unlike random_dfa_product in benchmark/cases/generators.jl, state 4
    # is a trap, so the reachability values are not identically 1.
    function dfa_product(rng, mdp)
        δ = Int32[
            1 2 3 4
            2 2 3 4
            4 3 3 4
            2 3 3 4
        ]
        dfa = DFA(TransitionFunction(δ), 1, ["a", "b"])
        # Labels "", a, b, ab with probability 0.4/0.2/0.2/0.2; the first four states
        # carry each label once (DeterministicLabelling needs all of 1:4 present).
        labels = Int32[
            i <= 4 ? i : (u = nextfloat!(rng); u < 0.4 ? 1 : u < 0.6 ? 2 : u < 0.8 ? 3 : 4) for
            i in 1:num_states(mdp)
        ]
        return ProductProcess(mdp, dfa, DeterministicLabelling(labels))
    end

    const REAL_MODEL_PATH =
        joinpath(pkgdir(IntervalMDP), "test", "data", "multiObj_robotIMDP")

    """
    Small versions of the case-matrix rows. Each entry: name => (; model, V, storage,
    product, problems) where problems maps an entry name to (problem, kind).
    """
    function cases()
        out = Pair{String, Any}[]
        for (storage, n, nnz, seed) in ((:dense, 12, 0, 0x01), (:sparse, 40, 5, 0x02))
            name = storage === :dense ? "imdp-dense" : "imdp-sparse"
            mdp, rng = random_imdp(seed; n, actions = 3, storage, nnz)
            V = input_values(rng, mdp)
            # Reach-avoid rather than plain reachability: with full-support random
            # models every state reaches the target almost surely (values ≡ 1),
            # which would make the comparison of converged values vacuous.
            reach = random_states(rng, n, 0.1)
            avoid = setdiff(random_states(rng, n, 0.2), reach)
            problems = Dict(
                "solve_rvi" => (
                    VerificationProblem(
                        mdp,
                        Specification(
                            InfiniteTimeReachAvoid(reach, avoid, CONV_EPS),
                            Pessimistic,
                            Maximize,
                        ),
                    ),
                    RobustValueIteration(OMaximization()),
                ),
                "solve_ivi" => (
                    VerificationProblem(
                        mdp,
                        Specification(
                            InfiniteTimeReachAvoid(reach, avoid, CONV_EPS),
                            Pessimistic,
                            Maximize,
                        ),
                    ),
                    IntervalValueIteration(OMaximization()),
                ),
            )
            push!(out, name => (; model = mdp, V, storage, product = false, problems))
        end
        for (storage, n, nnz, seed) in ((:dense, 10, 0, 0x03), (:sparse, 30, 4, 0x04))
            name = storage === :dense ? "product-dense-dfa4" : "product-sparse-dfa4"
            mdp, rng = random_imdp(seed; n, actions = 2, storage, nnz)
            prod = dfa_product(rng, mdp)
            V = input_values(rng, prod)
            spec = Specification(
                InfiniteTimeDFAReachability([3], CONV_EPS),
                Pessimistic,
                Maximize,
            )
            problems = Dict(
                "solve_dfa" => (
                    VerificationProblem(prod, spec),
                    RobustValueIteration(OMaximization()),
                ),
            )
            push!(out, name => (; model = prod, V, storage, product = true, problems))
        end
        for (storage, n, nnz, seed) in ((:dense, 12, 0, 0x05), (:sparse, 40, 6, 0x06))
            name = storage === :dense ? "cs-dense" : "cs-sparse"
            mdp, rng = random_imdp(seed; n, actions = 4, storage, nnz)
            V = input_values(rng, mdp)
            reach = random_states(rng, n, 0.1)
            avoid = setdiff(random_states(rng, n, 0.2), reach)
            inf = Specification(
                InfiniteTimeReachAvoid(reach, avoid, CONV_EPS),
                Pessimistic,
                Maximize,
            )
            fin = Specification(
                FiniteTimeReachAvoid(reach, avoid, CS_HORIZON),
                Pessimistic,
                Maximize,
            )
            problems = Dict(
                "solve_cs_stationary" => (
                    ControlSynthesisProblem(mdp, inf),
                    RobustValueIteration(OMaximization()),
                ),
                "solve_cs_timevarying" => (
                    ControlSynthesisProblem(mdp, fin),
                    RobustValueIteration(OMaximization()),
                ),
            )
            push!(out, name => (; model = mdp, V, storage, product = false, problems))
        end
        let
            cs = read_prism_file(REAL_MODEL_PATH)
            mdp = system(cs)
            spec = specification(cs)
            rng = LCG(0x07)
            V = input_values(rng, mdp)
            problems = Dict(
                "solve_rvi" => (
                    VerificationProblem(mdp, spec),
                    RobustValueIteration(OMaximization()),
                ),
                "solve_cs_stationary" => (
                    ControlSynthesisProblem(mdp, spec),
                    RobustValueIteration(OMaximization()),
                ),
            )
            push!(
                out,
                "real-multiObj_robotIMDP" =>
                    (; model = mdp, V, storage = :sparse, product = false, problems),
            )
        end
        return out
    end

    # Workspaces constructed directly. `:default` goes through construct_workspace
    # (depends on --threads); `:single` and `:threaded` pick the type explicitly.
    function omax_workspace(mdp, kind)
        kind === :default && return IntervalMDP.construct_workspace(mdp)
        prob = IntervalMDP.ambiguity_sets(IntervalMDP.marginals(mdp)[1])
        na = num_actions(mdp)
        dense = !(prob.lower isa SparseArrays.AbstractSparseMatrix)
        if kind === :single
            return dense ? IntervalMDP.DenseIntervalOMaxWorkspace(prob, na) :
                   IntervalMDP.SparseIntervalOMaxWorkspace(prob, na)
        else
            return dense ? IntervalMDP.ThreadedDenseIntervalOMaxWorkspace(prob, na) :
                   IntervalMDP.ThreadedSparseIntervalOMaxWorkspace(prob, na)
        end
    end

    function workspace(c, kind)
        c.product || return omax_workspace(c.model, kind)
        kind === :default && return IntervalMDP.construct_workspace(c.model)
        mp = markov_process(c.model)
        return IntervalMDP.ProductWorkspace(
            omax_workspace(mp, kind),
            zeros(IntervalMDP.valuetype(mp), Tuple(Int.(state_values(mp)))),
        )
    end

    expected_workspace_type(c, kind) =
        kind === :single ?
        (
            c.storage === :dense ? IntervalMDP.DenseIntervalOMaxWorkspace :
            IntervalMDP.SparseIntervalOMaxWorkspace
        ) :
        (
            c.storage === :dense ? IntervalMDP.ThreadedDenseIntervalOMaxWorkspace :
            IntervalMDP.ThreadedSparseIntervalOMaxWorkspace
        )

    "Whether the transition data of an IMDP lives on a device (not a CPU array)."
    function on_gpu(mdp)
        lower = IntervalMDP.ambiguity_sets(IntervalMDP.marginals(mdp)[1]).lower
        return !(lower isa Array) && !(lower isa SparseMatrixCSC)
    end

    underlying(ws) = ws isa IntervalMDP.ProductWorkspace ? ws.underlying_workspace : ws

    function run_bellman(c, kind, mode; to_dev = identity, to_host = Array, T = Float64)
        model = to_dev(c.model)
        V = to_dev(T.(c.V))
        ws = kind === :default ? IntervalMDP.construct_workspace(model) : workspace(c, kind)
        cache = IntervalMDP.construct_strategy_cache(model)
        Vres = similar(V)
        IntervalMDP.bellman!(ws, cache, Vres, V, model; mode...)
        return Float64.(vec(to_host(Vres))), ws
    end

    strategy_vector(s::StationaryStrategy) =
        Int[x for t in vec(Array(s.strategy)) for x in t]
    strategy_vector(s::TimeVaryingStrategy) =
        Int[x for st in s.strategy for t in vec(Array(st)) for x in t]

    "Value function (host Float64 vector), iterations and strategy (or empty) of a solve."
    function run_solve(problem, alg)
        sol = solve(problem, alg)
        strat =
            sol isa IntervalMDP.ControlSynthesisSolution ? strategy_vector(strategy(sol)) :
            Int[]
        return Float64.(vec(Array(value_function(sol)))), num_iterations(sol), strat, sol
    end

    "Value of the strategy of a control-synthesis solution by policy evaluation."
    policy_value(problem, alg, sol) = Float64.(
        vec(
            Array(
                value_function(
                    solve(
                        VerificationProblem(
                            system(problem),
                            specification(problem),
                            strategy(sol),
                        ),
                        alg,
                    ),
                ),
            ),
        ),
    )

    """
    All reference outcomes on the CPU with the single-threaded workspace (bellman) and
    the default algorithm path (solves). Keys: "<case>/bellman/<mode>",
    "<case>/<solve>/values", "<case>/<solve>/iterations", "<case>/<solve>/strategy".
    """
    function compute_outcomes()
        ref = Dict{String, Vector{Float64}}()
        for (name, c) in cases()
            for (mname, mode) in MODES
                ref["$name/bellman/$mname"] = first(run_bellman(c, :single, mode))
            end
            for (ename, (problem, alg)) in c.problems
                vals, k, strat, _ = run_solve(problem, alg)
                ref["$name/$ename/values"] = vals
                ref["$name/$ename/iterations"] = [k]
                isempty(strat) || (ref["$name/$ename/strategy"] = strat)
            end
        end
        return ref
    end

    # Reference text format: a key (contains '/') followed by its values (`repr` of each
    # Float64, so the round trip is exact), six per line.
    function reference_string(ref)
        io = IOBuffer()
        for k in sort!(collect(keys(ref)))
            println(io, k)
            for chunk in Iterators.partition(ref[k], 6)
                println(io, "    ", join(repr.(chunk), " "))
            end
        end
        return String(take!(io))
    end

    function parse_reference(s)
        ref = Dict{String, Vector{Float64}}()
        key = ""
        for tok in split(s)
            if occursin('/', tok)
                key = String(tok)
                ref[key] = Float64[]
            else
                push!(ref[key], parse(Float64, tok))
            end
        end
        return ref
    end

